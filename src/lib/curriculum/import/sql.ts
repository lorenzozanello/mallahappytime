/** Generates an idempotent SQL seed for Supabase from the parsed corpus (build-time only). */
import type { CurriculumCorpus } from '../types';

function q(v: string | number | null | undefined): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

function jsonb(v: unknown): string {
  return `${q(JSON.stringify(v))}::jsonb`;
}

function textArray(values: string[]): string {
  return `array[${values.map(q).join(', ')}]::text[]`;
}

export function corpusToSql(corpus: CurriculumCorpus): string {
  const { version } = corpus;
  const out: string[] = [
    '-- AUTO-GENERATED by scripts/import-curriculum.ts. Do not edit by hand.',
    `-- Source: ${version.sourceFile} (sha256 ${version.sourceSha256})`,
    'begin;',
    `insert into public.curriculum_versions (id, label, effective_date, source_file, source_sha256, status)
values (${q(version.id)}, ${q(version.label)}, ${q(version.effectiveDate)}, ${q(version.sourceFile)}, ${q(version.sourceSha256)}, 'active')
on conflict (id) do update set label = excluded.label, effective_date = excluded.effective_date,
  source_file = excluded.source_file, source_sha256 = excluded.source_sha256, status = 'active', imported_at = now();`,
    `update public.curriculum_versions set status = 'retired' where id <> ${q(version.id)} and status = 'active';`,
  ];

  for (const l of corpus.levels) {
    out.push(`insert into public.curriculum_levels (version_id, id, code, name, sort_order, cycle, equivalence, entry_age, exit_age, entry_profile, exit_profile, source_row)
values (${[version.id, l.id, l.code, l.name, l.order, l.cycle, l.equivalence, l.entryAge, l.exitAge, l.entryProfile, l.exitProfile, l.sourceRow].map(q).join(', ')})
on conflict (version_id, id) do update set code = excluded.code, name = excluded.name, sort_order = excluded.sort_order, cycle = excluded.cycle,
  equivalence = excluded.equivalence, entry_age = excluded.entry_age, exit_age = excluded.exit_age,
  entry_profile = excluded.entry_profile, exit_profile = excluded.exit_profile, source_row = excluded.source_row;`);
  }

  for (const e of corpus.experiences) {
    out.push(`insert into public.curriculum_experiences (version_id, id, level_id, period, period_label, period_code, title, fields, purposes, activities, source_row)
values (${q(version.id)}, ${q(e.id)}, ${q(e.levelId)}, ${e.period}, ${q(e.periodLabel)}, ${q(e.periodCode)}, ${q(e.title)}, ${jsonb(e.fields)}, ${jsonb(e.purposes)}, ${jsonb(e.activities)}, ${e.sourceRow})
on conflict (version_id, id) do update set level_id = excluded.level_id, period = excluded.period, period_label = excluded.period_label,
  period_code = excluded.period_code, title = excluded.title, fields = excluded.fields, purposes = excluded.purposes,
  activities = excluded.activities, source_row = excluded.source_row;`);
  }

  for (const d of corpus.developmentSummaries) {
    out.push(`insert into public.curriculum_development_summaries (version_id, id, level_id, dimension, content, source_reference)
values (${q(version.id)}, ${q(d.id)}, ${q(d.levelId)}, ${q(d.dimension)}, ${q(d.content)}, ${jsonb(d.sourceReference)})
on conflict (version_id, id) do update set level_id = excluded.level_id, dimension = excluded.dimension, content = excluded.content, source_reference = excluded.source_reference;`);
  }

  for (const p of corpus.principles) {
    out.push(`insert into public.curriculum_principles (version_id, id, sort_order, content, source_reference)
values (${q(version.id)}, ${q(p.id)}, ${p.order}, ${q(p.content)}, ${jsonb(p.sourceReference)})
on conflict (version_id, id) do update set sort_order = excluded.sort_order, content = excluded.content, source_reference = excluded.source_reference;`);
  }

  for (const c of corpus.chunks) {
    out.push(`insert into public.curriculum_chunks (curriculum_version, id, level_id, period, experience_id, section, subsection, content, tags, authority, source_reference, content_hash, status, updated_at)
values (${q(c.curriculumVersion)}, ${q(c.id)}, ${q(c.levelId)}, ${c.period ?? 'null'}, ${q(c.experienceId)}, ${q(c.section)}, ${q(c.subsection)}, ${q(c.content)}, ${textArray(c.tags)}, ${q(c.authority)}, ${jsonb(c.sourceReference)}, ${q(c.contentHash)}, ${q(c.status)}, ${q(c.updatedAt)})
on conflict (curriculum_version, id) do update set level_id = excluded.level_id, period = excluded.period, experience_id = excluded.experience_id,
  section = excluded.section, subsection = excluded.subsection, content = excluded.content, tags = excluded.tags, authority = excluded.authority,
  source_reference = excluded.source_reference, content_hash = excluded.content_hash, status = excluded.status, updated_at = excluded.updated_at,
  -- invalidate embeddings whose text changed
  embedding = case when public.curriculum_chunks.content_hash = excluded.content_hash then public.curriculum_chunks.embedding else null end;`);
  }

  // Chunks removed from the workbook are retired, never deleted (traceability).
  out.push(`update public.curriculum_chunks set status = 'retired'
where curriculum_version = ${q(version.id)} and id not in (${corpus.chunks.map((c) => q(c.id)).join(', ')});`);
  out.push('commit;', '');
  return out.join('\n\n');
}
